//! Read-only views over the guide set: ordering, `list`/`search` lines, the lint table and `index`.

use crate::guide::{CATEGORIES, Guide};
use crate::json::Value;
use std::collections::BTreeMap;
use std::fmt::Write as _;

fn category_rank(category: &str) -> usize {
    CATEGORIES
        .iter()
        .position(|&c| c == category)
        .unwrap_or(CATEGORIES.len())
}

/// Hubs first (in category order), then the other guides by category and ID.
pub fn hubs_first(guides: &[Guide]) -> Vec<&Guide> {
    let mut sorted: Vec<&Guide> = guides.iter().collect();
    sorted.sort_by_key(|g| (!g.is_hub(), category_rank(&g.category), g.id()));
    sorted
}

/// Category by category, each hub first.
fn by_category(guides: &[Guide]) -> Vec<&Guide> {
    let mut sorted: Vec<&Guide> = guides.iter().collect();
    sorted.sort_by_key(|g| {
        (
            category_rank(&g.category),
            g.category.as_str(),
            !g.is_hub(),
            g.id(),
        )
    });
    sorted
}

/// `id  [category, rust ≥ X]  description`
pub fn summary(guide: &Guide) -> String {
    format!(
        "{}  [{}, rust ≥ {}]  {}",
        guide.id(),
        guide.category,
        guide.version,
        guide.front.description
    )
}

/// `id  [category, rust ≥ X]  score  description`, with the score relative to the best hit.
pub fn search_line(guide: &Guide, score: f64) -> String {
    format!(
        "{}  [{}, rust ≥ {}]  {score:.2}  {}",
        guide.id(),
        guide.category,
        guide.version,
        guide.front.description
    )
}

pub fn to_json(guide: &Guide) -> Value {
    Value::object([
        ("id", Value::string(guide.id())),
        ("category", Value::string(guide.category.as_str())),
        ("hub", Value::Bool(guide.is_hub())),
        ("rust_version", Value::string(guide.version.to_string())),
        (
            "description",
            Value::string(guide.front.description.as_str()),
        ),
        ("clippy_lints", Value::strings(&guide.front.clippy_lints)),
    ])
}

/// Lint name → IDs of the guides that list it, both sorted.
pub fn lint_table(guides: &[Guide]) -> BTreeMap<String, Vec<String>> {
    let mut table: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for guide in guides {
        for lint in &guide.front.clippy_lints {
            let ids = table.entry(lint.clone()).or_default();
            if !ids.iter().any(|id| id == guide.id()) {
                ids.push(guide.id().to_owned());
            }
        }
    }
    for ids in table.values_mut() {
        ids.sort();
    }
    table
}

/// The markdown written to `skills/modern-rust-guidance/index.md`.
pub fn index(guides: &[Guide]) -> String {
    let mut out = String::from(
        "# Modern Rust Guidance index\n\nGenerated by `mrg index`; do not edit by hand. Run `mrg retrieve <id>`, or open `guides/<category>/<id>.md`.\n",
    );
    let mut current: Option<&str> = None;
    for guide in by_category(guides) {
        if current != Some(guide.category.as_str()) {
            current = Some(guide.category.as_str());
            let _ = write!(
                out,
                "\n## {}\n\n| ID | Rust | Description | Lints |\n| --- | --- | --- | --- |\n",
                guide.category
            );
        }
        let hub = if guide.is_hub() { " (hub)" } else { "" };
        let lints = if guide.front.clippy_lints.is_empty() {
            "—".to_owned()
        } else {
            guide
                .front
                .clippy_lints
                .iter()
                .map(|l| format!("`{l}`"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let description = guide.front.description.replace('|', "\\|");
        let _ = writeln!(
            out,
            "| `{}`{hub} | {} | {description} | {lints} |",
            guide.id(),
            guide.version
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::guide::tests::source;

    fn guides() -> Vec<Guide> {
        [
            "testing/testing.md",
            "std/zeta.md",
            "std/alpha.md",
            "std/std.md",
            "performance/performance.md",
        ]
        .iter()
        .map(|p| Guide::parse(&source(p, "1.80", "# T\n")).unwrap())
        .collect()
    }

    #[test]
    fn orders_hubs_first_or_by_category() {
        let guides = guides();
        let ids = |v: Vec<&Guide>| v.iter().map(|g| g.id().to_owned()).collect::<Vec<_>>();
        assert_eq!(
            ids(hubs_first(&guides)),
            ["std", "performance", "testing", "alpha", "zeta"]
        );
        assert_eq!(
            ids(by_category(&guides)),
            ["std", "alpha", "zeta", "performance", "testing"]
        );
    }

    #[test]
    fn lint_table_groups_guides() {
        let table = lint_table(&guides());
        assert_eq!(table.len(), 1);
        assert_eq!(
            table["manual_let_else"],
            ["alpha", "performance", "std", "testing", "zeta"]
        );
    }

    #[test]
    fn index_groups_by_category() {
        let text = index(&guides());
        assert!(text.contains("## std\n\n| ID | Rust | Description | Lints |"));
        let std_hub = text.find("| `std` (hub) | 1.80 |").unwrap();
        assert!(std_hub < text.find("| `alpha` |").unwrap());
        assert!(text.find("## std").unwrap() < text.find("## performance").unwrap());
        assert!(text.contains("| `manual_let_else` |") || text.contains("`manual_let_else` |"));
    }

    #[test]
    fn summary_line() {
        let guide = &guides()[2];
        assert_eq!(
            summary(guide),
            "alpha  [std, rust ≥ 1.80]  Do the alpha thing."
        );
    }
}
